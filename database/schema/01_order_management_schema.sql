-- 01_order_management_schema.sql
-- Realistic order-management dataset schema for PostgreSQL Tuning Tools evaluation.
-- Target scale: 20,000 customers and 500,000 orders (plus pgbench scale factor 50).

CREATE TABLE IF NOT EXISTS customers (
    customer_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code   VARCHAR(24) NOT NULL UNIQUE,
    full_name       VARCHAR(120) NOT NULL,
    email           VARCHAR(160) NOT NULL UNIQUE,
    phone           VARCHAR(32) NOT NULL,
    region          VARCHAR(24) NOT NULL,
    segment         VARCHAR(24) NOT NULL,
    country         VARCHAR(48) NOT NULL,
    loyalty_points  INTEGER NOT NULL DEFAULT 0,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS orders (
    order_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      INTEGER NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    order_status     VARCHAR(24) NOT NULL,
    order_date       TIMESTAMPTZ NOT NULL,
    total_amount     NUMERIC(12, 2) NOT NULL,
    shipping_region  VARCHAR(24) NOT NULL,
    payment_method   VARCHAR(24) NOT NULL,
    priority_flag    BOOLEAN NOT NULL DEFAULT FALSE,
    notes            TEXT NOT NULL
);

-- Baseline foreign-key index (clean baseline).
-- Additional indexes are intentionally managed via scenario & optimization scripts.
CREATE INDEX IF NOT EXISTS idx_orders_customer_id ON orders (customer_id);

COMMENT ON TABLE customers IS 'Order-management customer dimension (~20,000 rows).';
COMMENT ON TABLE orders IS 'Order-management fact table (~500,000 rows).';
